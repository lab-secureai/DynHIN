#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
analyze_group_d.py — Four diagnostic analyses that run on CPU in a few minutes.

They are benchmark sanity checks that need neither a
GPU nor rerunning the experiments:

  D1  SHORTCUT PROBE — is the benign-vs-malware task on CIC-YNU-IoTMal really
      malware detection? The benign class was generated by GPT-4.1-mini
      (Dadkhah et al. 2026, section 3.3) while the malware class consists of real
      binaries, so a simple linear model may separate the two classes by traces
      of the generation process rather than by malicious behaviour. If logistic
      regression reaches ~0.99, this must be stated clearly in the Limitations.

  D2  ARCHITECTURE LEAKAGE — the number of features varies by architecture (40 PCAP
      + 392–461 SAR/STRACE). The pipeline reads with union_by_name and then fills
      missing columns with 0, so the pattern of all-zero columns may encode the CPU
      architecture itself. Since each architecture has a different malware family
      composition (only ARM has Tsunami/Agent, only ARM has malware > benign),
      this is an indirect label-leakage path.

  D3  NEAR-DUPLICATES — splitting by Hash blocks exact copies but does NOT block
      near-duplicate samples with different Hashes. With 95.7% of the malware being
      Mirai, this is a plausible explanation for ROC-AUC = 1.0000 ± 0.0000.

  D4  FILTERING STATISTICS — merge(how='inner') drops every sample that lacks any
      modality. We need to know how many are lost, in which families, and where the
      'Botnet' family (present in Table 7 of the dataset paper) goes.

Usage
-----
    python3 analyze_group_d.py \\
        --parquet cached_merged_multimodal.parquet \\
        --data-dir /kaggle/input/cic-ynu-iotmal \\
        --out-dir diagnostics

`--data-dir` is only needed for D4 (reads the raw pcap/sar/strace per architecture).

Dependencies: pandas, numpy, scikit-learn. duckdb is only needed for D4.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from typing import Dict, List

import numpy as np
import pandas as pd

REPORT: List[str] = []


def say(line: str = "") -> None:
    print(line)
    REPORT.append(line)


# =========================================================================
# Shared utilities — replicate EXACTLY how the pipeline groups columns and splits data
# =========================================================================

PCAP_NAMES = ['Header_Length', 'Protocol Type', 'Time_To_Live', 'Rate', 'Tot sum',
              'Min', 'Max', 'AVG', 'Std', 'Tot size', 'IAT', 'Number', 'Variance']
PROTO_NAMES = ['TCP', 'UDP', 'ICMP', 'HTTP', 'HTTPS', 'DNS', 'Telnet', 'SSH',
               'IRC', 'DHCP', 'ARP', 'IGMP', 'IPv', 'LLC']


def split_feature_groups(df: pd.DataFrame) -> Dict[str, List[str]]:
    cols = df.columns.tolist()
    syscall = [c for c in cols if c.startswith('Call_') or 'syscall' in c.lower()]
    proto = [c for c in PROTO_NAMES if c in cols]
    exclude = set(['label', 'arch', 'Arch', 'Hash', 'MalwareFamily',
                   'stratify_col'] + syscall + proto)
    pcap = [c for c in cols if c in PCAP_NAMES
            or c.endswith('_flag_number') or c.endswith('_count')]
    sar = [c for c in cols if c not in exclude and c not in pcap]
    return {"pcap": pcap, "sar": sar, "syscall": syscall, "proto": proto}


def clean_matrix(df: pd.DataFrame, cols: List[str]) -> np.ndarray:
    if not cols:
        return np.zeros((len(df), 0), dtype=np.float32)
    v = df[cols].replace([np.inf, -np.inf], np.nan).fillna(0).values
    v = np.nan_to_num(v, nan=0.0, posinf=1e9, neginf=-1e9)
    return np.clip(v, -1e9, 1e9).astype(np.float32)


def group_safe_split(df: pd.DataFrame, seed: int = 42, test_size: float = 0.2):
    """Simplified version of group_safe_stratified_split from the pipeline."""
    from sklearn.model_selection import StratifiedGroupKFold, GroupShuffleSplit
    strat = df['label'].astype(str) + '_' + df.get(
        'arch', pd.Series(['NA'] * len(df), index=df.index)).astype(str)
    groups = df['Hash'].astype(str).values
    n_splits = max(2, min(int(round(1.0 / test_size)), df['Hash'].nunique()))
    try:
        sgkf = StratifiedGroupKFold(n_splits=n_splits, shuffle=True, random_state=seed)
        tr, te = next(iter(sgkf.split(df, strat.values, groups=groups)))
    except ValueError:
        tr, te = next(GroupShuffleSplit(n_splits=1, test_size=test_size,
                                        random_state=seed).split(df, strat.values, groups=groups))
    assert not (set(groups[tr]) & set(groups[te])), "Hash leakage between train and test!"
    return df.iloc[tr].reset_index(drop=True), df.iloc[te].reset_index(drop=True)


# =========================================================================
# D1 — SHORTCUT PROBE
# =========================================================================

def d1_shortcut_probe(df: pd.DataFrame, groups: Dict[str, List[str]],
                      seeds: List[int], out_dir: str) -> None:
    from sklearn.linear_model import LogisticRegression
    from sklearn.tree import DecisionTreeClassifier
    from sklearn.preprocessing import StandardScaler
    from sklearn.metrics import f1_score, roc_auc_score, accuracy_score

    say("\n" + "=" * 78)
    say("D1 — SHORTCUT PROBE: how easy is this task for a trivial model?")
    say("=" * 78)
    say("If logistic regression reaches ~0.99, the advantage of R-HGT does not come from")
    say("modelling behaviour, and the whole clean benchmark loses its discriminative power.")
    say("Note: the benign class of CIC-YNU-IoTMal consists of C programs generated by GPT-4.1-mini;")
    say("malware are real binaries. The two classes also differ in provenance.\n")

    feature_sets = {
        "PCAP": groups["pcap"],
        "SAR": groups["sar"],
        "STRACE": groups["syscall"],
        "ALL": groups["pcap"] + groups["sar"] + groups["syscall"],
    }
    rows = []
    for fs_name, cols in feature_sets.items():
        if not cols:
            continue
        for seed in seeds:
            tr, te = group_safe_split(df, seed=seed)
            Xtr, Xte = clean_matrix(tr, cols), clean_matrix(te, cols)
            ytr, yte = tr['label'].values, te['label'].values
            sc = StandardScaler().fit(Xtr)
            Xtr_s, Xte_s = sc.transform(Xtr), sc.transform(Xte)

            for clf_name, clf in [
                ("Logistic Regression", LogisticRegression(max_iter=2000, n_jobs=-1)),
                ("Decision Tree (depth 3)", DecisionTreeClassifier(max_depth=3, random_state=seed)),
                ("Decision Tree (1 stump)", DecisionTreeClassifier(max_depth=1, random_state=seed)),
            ]:
                X_a, X_b = (Xtr_s, Xte_s) if "Logistic" in clf_name else (Xtr, Xte)
                clf.fit(X_a, ytr)
                p = clf.predict_proba(X_b)[:, 1]
                rows.append({
                    "Feature set": fs_name, "Model": clf_name, "Seed": seed,
                    "Accuracy": accuracy_score(yte, (p >= .5).astype(int)),
                    "F1": f1_score(yte, (p >= .5).astype(int), zero_division=0),
                    "ROC-AUC": roc_auc_score(yte, p),
                })

    res = pd.DataFrame(rows)
    summ = (res.groupby(["Feature set", "Model"])[["Accuracy", "F1", "ROC-AUC"]]
            .agg(["mean", "std"]).round(4))
    say(summ.to_string())
    res.to_csv(os.path.join(out_dir, "d1_shortcut_probe_raw.csv"), index=False)

    best = res.groupby("Model")["F1"].mean().max()
    stump = res[res["Model"].str.contains("1 stump")]["F1"].mean()
    say("")
    if best > 0.98:
        say(f"⚠️  CONCLUSION: a trivial model reaches F1 = {best:.4f}. The binary")
        say("    task on this dataset is ALREADY SATURATED — it cannot distinguish")
        say("    methods. You must (a) state this clearly in the Limitations, and (b) shift the focus")
        say("    to conditions that are not yet saturated: adversarial, LOFO, the protocol")
        say("    gap, or the multi-class family task.")
    if np.isfinite(stump) and stump > 0.90:
        say(f"⚠️  A ONE-SPLIT decision tree reaches F1 = {stump:.4f}. That is, a single")
        say("    threshold on one feature suffices. This is a clear signature of a")
        say("    shortcut; print that feature and check what it means.")


# =========================================================================
# D2 — ARCHITECTURE LEAKAGE
# =========================================================================

def d2_arch_leakage(df: pd.DataFrame, groups: Dict[str, List[str]],
                    seeds: List[int], out_dir: str) -> None:
    from sklearn.linear_model import LogisticRegression
    from sklearn.preprocessing import StandardScaler
    from sklearn.metrics import accuracy_score

    say("\n" + "=" * 78)
    say("D2 — ARCHITECTURE LEAKAGE: can the CPU arch be inferred from the feature vector?")
    say("=" * 78)

    cols = groups["pcap"] + groups["sar"] + groups["syscall"]
    X_all = clean_matrix(df, cols)

    # (a) Pattern of all-zero columns per architecture — a trace of union_by_name + fillna(0).
    say("\n(a) Number of columns that are ENTIRELY 0 in each architecture "
        "(columns that only exist in other architectures):")
    zero_profile = {}
    for arch, sub in df.groupby(df['arch'].astype(str)):
        Xa = clean_matrix(sub, cols)
        allzero = int((np.abs(Xa).max(axis=0) == 0).sum())
        zero_profile[arch] = allzero
        say(f"      {arch:8s}: {allzero:4d} / {len(cols)} all-zero columns "
            f"({allzero / max(len(cols), 1):.1%})")
    if len(set(zero_profile.values())) > 1:
        say("    ⚠️  The all-zero-column pattern DIFFERS across architectures → the pattern")
        say("        of missingness alone is enough to identify the architecture.")

    # (b) Architecture classifier.
    rows = []
    for seed in seeds:
        tr, te = group_safe_split(df, seed=seed)
        sc = StandardScaler().fit(clean_matrix(tr, cols))
        clf = LogisticRegression(max_iter=1000, n_jobs=-1)
        clf.fit(sc.transform(clean_matrix(tr, cols)), tr['arch'].astype(str))
        acc = accuracy_score(te['arch'].astype(str),
                             clf.predict(sc.transform(clean_matrix(te, cols))))
        rows.append({"Seed": seed, "Arch accuracy": acc})
    r = pd.DataFrame(rows)
    base = df['arch'].value_counts(normalize=True).max()
    say(f"\n(b) Predicting architecture from features: accuracy = "
        f"{r['Arch accuracy'].mean():.4f} ± {r['Arch accuracy'].std(ddof=1):.4f}")
    say(f"    Majority-class baseline: {base:.4f}")
    r.to_csv(os.path.join(out_dir, "d2_arch_leakage.csv"), index=False)

    if r['Arch accuracy'].mean() > 0.95:
        say("    ⚠️  The architecture can be inferred almost perfectly. Since the malware family composition")
        say("        differs by architecture (only ARM has Tsunami/Agent; only ARM has")
        say("        malware > benign), this is an indirect label-leakage path. Remedy:")
        say("        take the INTERSECTION of the columns shared by all 4 architectures, or add explicit")
        say("        missing-indicator columns instead of silently filling with 0.")

    # (c) Label imbalance across architectures — explains the ARM anomaly.
    say("\n(c) Label ratio by architecture (explains why ARM is the exception):")
    tab = (df.groupby(df['arch'].astype(str))['label']
           .agg(n='size', malware='sum'))
    tab['benign'] = tab['n'] - tab['malware']
    tab['malware rate'] = (tab['malware'] / tab['n']).round(4)
    say(tab.to_string())
    say("    → An architecture with malware > benign heavily penalises a model with low recall")
    say("      there. This partly explains why")
    say("      MAGNN/RGCN/GAT collapse on ARM but behave normally elsewhere.")


# =========================================================================
# D3 — NEAR-DUPLICATES
# =========================================================================

def d3_near_duplicates(df: pd.DataFrame, groups: Dict[str, List[str]],
                       seed: int, out_dir: str) -> None:
    from sklearn.neighbors import NearestNeighbors
    from sklearn.preprocessing import StandardScaler

    say("\n" + "=" * 78)
    say("D3 — NEAR-DUPLICATES between train and test (a split by Hash does NOT block them)")
    say("=" * 78)

    cols = groups["pcap"] + groups["sar"] + groups["syscall"]
    tr, te = group_safe_split(df, seed=seed)
    sc = StandardScaler().fit(clean_matrix(tr, cols))
    Xtr = np.nan_to_num(sc.transform(clean_matrix(tr, cols)))
    Xte = np.nan_to_num(sc.transform(clean_matrix(te, cols)))

    nn = NearestNeighbors(n_neighbors=1, metric="cosine", n_jobs=-1).fit(Xtr)
    dist, idx = nn.kneighbors(Xte)
    dist = dist.ravel()

    say(f"\nCosine distance to the nearest train neighbour "
        f"({len(te):,} test samples, seed {seed}):")
    for q in [0, 1, 5, 10, 25, 50, 75, 95, 100]:
        say(f"      percentile {q:3d}%: {np.percentile(dist, q):.6f}")
    for thr in [1e-6, 1e-4, 1e-3, 1e-2]:
        frac = float((dist < thr).mean())
        say(f"      fraction of test samples with distance < {thr:g}: {frac:.2%}")

    same_label = (tr['label'].values[idx.ravel()] == te['label'].values)
    say(f"\n      Nearest neighbour has the SAME LABEL: {same_label.mean():.2%}")

    out = pd.DataFrame({
        "test_hash": te['Hash'].astype(str).values,
        "test_label": te['label'].values,
        "test_family": te['MalwareFamily'].astype(str).values
                        if 'MalwareFamily' in te.columns else "",
        "test_arch": te['arch'].astype(str).values,
        "nn_cosine_distance": dist,
        "nn_train_hash": tr['Hash'].astype(str).values[idx.ravel()],
        "nn_same_label": same_label,
    })
    out.to_csv(os.path.join(out_dir, "d3_near_duplicates.csv"), index=False)

    say("\nMedian distance by family (which family is most duplicated?):")
    if 'MalwareFamily' in te.columns:
        say(out.groupby("test_family")["nn_cosine_distance"]
            .agg(n="size", median="median", p10=lambda s: s.quantile(.10))
            .round(6).sort_values("median").to_string())

    if float((dist < 1e-3).mean()) > 0.10:
        say("\n⚠️  More than 10% of test samples nearly coincide with a train sample despite a different")
        say("    Hash. Splitting by Hash is NOT enough. This number must be reported, and")
        say("    consider splitting by behavioural cluster instead of by Hash.")


# =========================================================================
# D4 — FILTERING STATISTICS
# =========================================================================

def d4_filtering_stats(df: pd.DataFrame, data_dir: str, out_dir: str) -> None:
    say("\n" + "=" * 78)
    say("D4 — FILTERING STATISTICS: what does merge(how='inner') remove?")
    say("=" * 78)

    say("\nFinal set used for the experiments:")
    say(f"      total samples (Hash × arch): {len(df):,}")
    say(f"      distinct Hash count:         {df['Hash'].nunique():,}")
    if 'MalwareFamily' in df.columns:
        fam = df['MalwareFamily'].astype(str).value_counts()
        say("\n      By family:")
        for k, v in fam.items():
            say(f"        {k:14s} {v:7,d}  ({v / len(df):6.2%})")
        if 'Botnet' not in fam.index:
            say("\n      ⚠️  Family 'Botnet' is NOT in the final set, although Table 7 of the")
            say("          dataset paper lists it under MIPS, MIPSEL and x86. Determine")
            say("          at which step it is dropped and state this in the paper.")

    say("\n      By architecture × label:")
    say(pd.crosstab(df['arch'].astype(str), df['label']).to_string())

    if not data_dir or not os.path.isdir(data_dir):
        say("\n[skipping comparison with the raw data: no valid --data-dir given]")
        return

    try:
        import duckdb
    except ImportError:
        say("\n[skipping comparison: duckdb is not installed]")
        return

    say("\nComparison with the raw parquet (distinct Hash count before the merge):")
    con = duckdb.connect(database=':memory:')
    rows = []
    for arch in ['arm', 'mips', 'mipsel', 'x86']:
        adir = os.path.join(data_dir, arch)
        rec = {"arch": arch}
        sets = {}
        for mod in ['pcap', 'sar', 'strace']:
            p = os.path.join(adir, f"{mod}.parquet")
            if not os.path.exists(p):
                rec[mod] = None
                continue
            try:
                q = con.execute(
                    f"SELECT COUNT(DISTINCT \"Hash\") FROM read_parquet('{p}', union_by_name=True)"
                ).fetchone()[0]
                rec[mod] = int(q)
                sets[mod] = set(con.execute(
                    f"SELECT DISTINCT \"Hash\" FROM read_parquet('{p}', union_by_name=True)"
                ).df()['Hash'].astype(str))
            except Exception as e:                                  # noqa: BLE001
                rec[mod] = f"error: {e}"[:40]
        if len(sets) == 3:
            inter = set.intersection(*sets.values())
            rec["in all 3 modalities"] = len(inter)
            rec["in final set"] = int(
                (df['arch'].astype(str) == arch).sum())
            rec["lost to inner join"] = (max(sets, key=lambda k: len(sets[k]))
                                        and len(set.union(*sets.values())) - len(inter))
        rows.append(rec)
    con.close()
    t = pd.DataFrame(rows)
    say(t.to_string(index=False))
    t.to_csv(os.path.join(out_dir, "d4_filtering_stats.csv"), index=False)
    say("\n→ Column 'lost to inner join' is the number of samples dropped because at least one")
    say("  modality is missing. This number must appear in the paper as a declared")
    say("  sample-selection bias.")


# =========================================================================
# MAIN
# =========================================================================

def main() -> None:
    ap = argparse.ArgumentParser(description="Four group-D diagnostic analyses.")
    ap.add_argument("--parquet", default="cached_merged_multimodal.parquet")
    ap.add_argument("--data-dir", default="", help="Directory containing arm/ mips/ ... (for D4)")
    ap.add_argument("--out-dir", default="diagnostics")
    ap.add_argument("--seeds", default="10,42,100")
    ap.add_argument("--only", default="", help="Run a selection, e.g. 'D1,D3'")
    args = ap.parse_args()

    if not os.path.exists(args.parquet):
        sys.exit(f"Cannot find {args.parquet}. Run the pipeline once to generate the cache, "
                 f"or point --parquet to the correct file.")
    os.makedirs(args.out_dir, exist_ok=True)
    seeds = [int(s) for s in args.seeds.split(',') if s.strip()]
    want = {w.strip().upper() for w in args.only.split(',') if w.strip()} or {
        "D1", "D2", "D3", "D4"}

    say(f"Loading {args.parquet} ...")
    df = pd.read_parquet(args.parquet)
    if 'label' not in df.columns and 'MalwareFamily' in df.columns:
        df['label'] = (df['MalwareFamily'].astype(str).str.lower() != 'benign').astype(int)
    say(f"  {len(df):,} rows × {df.shape[1]:,} columns")

    groups = split_feature_groups(df)
    say(f"  Feature groups: PCAP={len(groups['pcap'])}, SAR={len(groups['sar'])}, "
        f"STRACE={len(groups['syscall'])}, PROTO={len(groups['proto'])}")
    say("  (The dataset paper reports PCAP = 40 and SAR+STRACE = 392–461 features. If the numbers")
    say("   above deviate a lot, the column-grouping heuristic in the pipeline is wrong.)")
    json.dump({k: v for k, v in groups.items()},
              open(os.path.join(args.out_dir, "feature_groups.json"), "w"),
              ensure_ascii=False, indent=2)

    if "D1" in want:
        d1_shortcut_probe(df, groups, seeds, args.out_dir)
    if "D2" in want:
        d2_arch_leakage(df, groups, seeds, args.out_dir)
    if "D3" in want:
        d3_near_duplicates(df, groups, seeds[0], args.out_dir)
    if "D4" in want:
        d4_filtering_stats(df, args.data_dir, args.out_dir)

    p = os.path.join(args.out_dir, "GROUP_D_REPORT.md")
    with open(p, "w", encoding="utf-8") as f:
        f.write("# Group D diagnostic report\n\n```\n")
        f.write("\n".join(REPORT))
        f.write("\n```\n")
    print(f"\n✅ Report: {p}")


if __name__ == "__main__":
    main()
